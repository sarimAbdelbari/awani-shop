const mongoose = require('mongoose');

const productSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  price: {
    type: Number,
    required: true,
  },
  description: {
    type: String,
    required: true,
  },
  image: {
    type: String,
    required: true,
  },
});


// price de achat, price de vente, quantity, category, brand, supplier, createdAt, updatedAt

module.exports = mongoose.model('Product', productSchema);